#!/usr/bin/env python3
"""Turns domain lists into the resolver's block zone for the AmneziaWG DNS filter.

    python3 blocklist.py --out /var/lib/awg/dns/blocklist.conf LIST [LIST ...]

Each LIST is a plain file with one domain per line (hosts-file lines and comments
are accepted too). The output is an unbound include file: every domain answers
NXDOMAIN together with its subdomains. The file is replaced only when it passes
the checks below; otherwise the previous file stays, so a bad download never
turns the filter off by accident and never blocks everything.

Limits are a safety net, not a policy: they reject an empty or truncated list
and a list so large that the resolver would not fit in the server's memory.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from collections.abc import Iterable
from pathlib import Path

MIN_DOMAINS = 1_000
MAX_DOMAINS = 2_500_000
LABEL = r"[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?"
DOMAIN_RE = re.compile(rf"^(?:{LABEL}\.)+[a-z0-9-]{{2,63}}$")
ALWAYS_ALLOWED = frozenset({"localhost", "local"})


def normalize(line: str) -> str | None:
    """A domain from one input line, or None for comments, blanks and bad names."""
    text = line.split("#", 1)[0].strip().lower()
    if not text:
        return None
    parts = text.split()
    # hosts-file form: "0.0.0.0 example.com" or "127.0.0.1 example.com"
    name = parts[-1] if len(parts) >= 2 else parts[0]
    name = name.rstrip(".")
    if name.startswith("*."):
        name = name[2:]
    if name in ALWAYS_ALLOWED or not DOMAIN_RE.fullmatch(name):
        return None
    return name


def parse(lines: Iterable[str]) -> set[str]:
    found: set[str] = set()
    for line in lines:
        name = normalize(line)
        if name is not None:
            found.add(name)
    return found


def render(domains: Iterable[str]) -> str:
    body = "".join(
        f'local-zone: "{name}" always_nxdomain\n' for name in sorted(domains)
    )
    header = (
        "# Generated by deploy/awg/dns/blocklist.py. Do not edit by hand.\n"
        "# Domains answer NXDOMAIN together with their subdomains.\n"
    )
    return header + body


def check_count(count: int) -> None:
    if count < MIN_DOMAINS:
        raise ValueError(f"only {count} domains; the list looks truncated")
    if count > MAX_DOMAINS:
        raise ValueError(f"{count} domains is above the {MAX_DOMAINS} limit")


def write_atomic(path: Path, text: str) -> None:
    """Write next to the target and rename, so the resolver never reads half a file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp")
    temp.write_text(text, encoding="utf-8")
    os.replace(temp, path)


def build(inputs: list[Path], out: Path) -> int:
    domains: set[str] = set()
    for source in inputs:
        with source.open(encoding="utf-8", errors="replace") as handle:
            domains |= parse(handle)
    check_count(len(domains))
    write_atomic(out, render(domains))
    return len(domains)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("inputs", nargs="+", type=Path)
    args = parser.parse_args(argv)
    try:
        count = build(args.inputs, args.out)
    except (OSError, ValueError) as exc:
        print(f"DNS_BLOCKLIST_KEPT: {exc}. The previous file stays.", file=sys.stderr)
        return 1
    print(f"DNS_BLOCKLIST_OK: {count} domains in {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
